CREATE TABLE public.formulario_requisito (
    id_formulario_requisito bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_formulario bigint,
    codigo text,
    nombre text,
    descripcion text,
    minimo integer NOT NULL DEFAULT 0,
