CREATE TABLE public.tipo_tramite (
    id_tipo_tramite bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo text,
    nombre text,
    descripcion text,
    activo boolean NOT NULL DEFAULT false,
    permite_solicitud boolean NOT NULL DEFAULT false,
    orden integer NOT NULL DEFAULT 0
);
CREATE TABLE public.formulario (
    id_formulario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo_tramite bigint,
    nombre text,
    numero_version integer NOT NULL DEFAULT 0,
    estado text,
    version bigint NOT NULL DEFAULT 0,
    creado_por bigint,
    actualizado_por bigint,
    creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fundamento_publicacion text,
    publicado_en timestamptz
);
CREATE TABLE public.formulario_seccion (
    id_formulario_seccion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_formulario bigint,
    codigo text,
    titulo text,
    orden integer NOT NULL DEFAULT 0
);
CREATE TABLE public.formulario_grupo (
