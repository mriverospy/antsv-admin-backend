CREATE TABLE public.formulario_regla (
    id_formulario_regla bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_formulario bigint,
    origen text,
    destino text,
    operador text,
    valor text,
    accion text
);
CREATE TABLE public.tramite (
    id_tramite bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero text,
    id_formulario bigint,
    id_solicitante bigint,
    id_responsable bigint,
    estado text,
    version bigint NOT NULL DEFAULT 0,
    creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    presentado_en timestamptz,
    finalizado_en timestamptz
);
CREATE TABLE public.tramite_grupo_instancia (
    id_tramite_grupo_instancia bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tramite bigint,
    id_formulario bigint,
    grupo text,
    instancia text,
    orden integer NOT NULL DEFAULT 0
);
CREATE TABLE public.tramite_respuesta (
    id_tramite_respuesta bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tramite bigint,
    id_formulario bigint,
    campo text,
    instancia text,
    valor_texto text,
    valor_numero numeric,
    valor_fecha date,
    valor_booleano boolean,
    valor_json jsonb
);
CREATE TABLE public.tramite_archivo (
    id_tramite_archivo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tramite bigint,
    id_formulario bigint,
    requisito text,
    referencia text,
    nombre text,
    mime text,
    tamanio bigint NOT NULL DEFAULT 0,
    hash text,
    activo boolean NOT NULL DEFAULT false,
    creado_por bigint,
    creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.tramite_evento (
    id_tramite_evento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tramite bigint,
    id_usuario bigint,
    accion text,
    estado_anterior text,
    estado_nuevo text,
    observacion text,
    visible_solicitante boolean NOT NULL DEFAULT false,
    fecha timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.tramite_revision (
    id_tramite_revision bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tramite bigint,
    id_usuario bigint,
    version_presentada bigint,
    clave_presentacion text,
    contenido jsonb,
    fecha timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

